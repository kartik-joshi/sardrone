"""The scorecard: one row per model version.

    docs/results/scorecard.csv     the data
    docs/results/scorecard.md      the same, readable

Each row holds a model's score on the simulated test set and on the real
one, and the difference between them, the SIM-TO-REAL GAP, with a 95 %
confidence interval. A row is replaced, never duplicated, when a version is
evaluated again; and every row names the commit and the training-data hash
it came from, so no number in it is an orphan.
"""

import csv
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

from sardrone.train.metrics import (
    ImageResult,
    Scores,
    bootstrap_map,
    gap_interval,
    interval,
    score,
)

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CSV = PROJECT_ROOT / "docs" / "results" / "scorecard.csv"

FIELDS = [
    "version", "change", "train_hash", "train_images", "commit", "confidence",
    "sim_map50", "sim_map50_low", "sim_map50_high", "sim_map50_95", "sim_precision", "sim_recall",
    "real_map50", "real_map50_low", "real_map50_high", "real_map50_95", "real_precision", "real_recall",
    "gap_map50", "gap_map50_low", "gap_map50_high", "sim_images", "real_images", "evaluated_utc",
]  # fmt: skip


def images_from_view(view, pred_field: str, gt_field: str = "ground_truth", label: str = "person") -> list[ImageResult]:
    """Turn a FiftyOne view into the plain structure metrics.py works on.

    Boxes stay in FiftyOne's 0..1 units. IoU is a ratio of areas, so it is
    the same whether measured in fractions or in pixels.
    """

    def corners(box):
        x, y, w, h = box
        return (x, y, x + w, y + h)

    images = []
    for truths, predictions in zip(view.values(gt_field), view.values(pred_field)):
        images.append(
            ImageResult(
                truths=tuple(corners(d.bounding_box) for d in (truths.detections if truths else []) if d.label == label),
                predictions=tuple(
                    (float(d.confidence), corners(d.bounding_box))
                    for d in (predictions.detections if predictions else [])
                    if d.label == label
                ),
            )
        )
    return images


@dataclass
class Evaluation:
    scores: Scores
    map50_interval: tuple[float, float]
    map50_95_interval: tuple[float, float]
    samples: np.ndarray  # bootstrap draws, kept for the gap


def evaluate(images: list[ImageResult], confidence: float | None = None, repeats: int = 1000, seed: int = 0) -> Evaluation:
    scores, matched = score(images, confidence)
    samples = bootstrap_map(matched, repeats, seed)
    return Evaluation(scores, interval(samples[:, 0]), interval(samples[:, 1]), samples)


def scorecard_row(version: str, change: str, sim: Evaluation, real: Evaluation, *, train_hash: str,
                  train_images: int, commit: str, evaluated_utc: str) -> dict:  # fmt: skip
    gap_low, gap_high = gap_interval(sim.samples[:, 0], real.samples[:, 0])

    def r(value):
        return round(float(value), 4)

    return {
        "version": version, "change": change, "train_hash": train_hash, "train_images": train_images,
        "commit": commit, "confidence": r(sim.scores.confidence),
        "sim_map50": r(sim.scores.map50), "sim_map50_low": r(sim.map50_interval[0]),
        "sim_map50_high": r(sim.map50_interval[1]), "sim_map50_95": r(sim.scores.map50_95),
        "sim_precision": r(sim.scores.precision), "sim_recall": r(sim.scores.recall),
        "real_map50": r(real.scores.map50), "real_map50_low": r(real.map50_interval[0]),
        "real_map50_high": r(real.map50_interval[1]), "real_map50_95": r(real.scores.map50_95),
        "real_precision": r(real.scores.precision), "real_recall": r(real.scores.recall),
        "gap_map50": r(sim.scores.map50 - real.scores.map50), "gap_map50_low": r(gap_low),
        "gap_map50_high": r(gap_high), "sim_images": sim.scores.images, "real_images": real.scores.images,
        "evaluated_utc": evaluated_utc,
    }  # fmt: skip


def read_scorecard(path: Path = DEFAULT_CSV) -> list[dict]:
    if not Path(path).exists():
        return []
    with open(path, newline="") as handle:
        return list(csv.DictReader(handle))


def write_scorecard(rows: list[dict], path: Path = DEFAULT_CSV) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows({field: row.get(field, "") for field in FIELDS} for row in rows)

    def cell(row, key):
        return f"{float(row[key]):.3f} ({float(row[key + '_low']):.3f} to {float(row[key + '_high']):.3f})"

    lines = [
        "# Scorecard",
        "",
        "Generated by `sardrone.train.scorecard`. Do not edit by hand; the numbers",
        "come from `scorecard.csv`. mAP@0.5 for `person`, with 95 % bootstrap",
        "intervals. Gap = simulated minus real: the smaller, the better the transfer.",
        "",
        "| Version | Change | Sim mAP@0.5 | Real mAP@0.5 | Gap | Sim P / R | Real P / R | Train images | Data hash | Commit |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['version']} | {row['change']} | {cell(row, 'sim_map50')} | {cell(row, 'real_map50')} | "
            f"{cell(row, 'gap_map50')} | {float(row['sim_precision']):.2f} / {float(row['sim_recall']):.2f} | "
            f"{float(row['real_precision']):.2f} / {float(row['real_recall']):.2f} | {row['train_images']} | "
            f"`{row['train_hash']}` | `{row['commit']}` |"
        )
    lines += ["", "Precision and recall are at the confidence cut-off chosen on the validation set", "(column `confidence` in the CSV), IoU 0.5.", ""]
    path.with_suffix(".md").write_text("\n".join(lines))


def upsert(row: dict, path: Path = DEFAULT_CSV) -> list[dict]:
    """Add the row, replacing an existing row for the same version."""
    rows = [existing for existing in read_scorecard(path) if existing["version"] != row["version"]]
    rows.append({key: str(value) for key, value in row.items()})
    rows.sort(key=lambda existing: existing["version"])
    write_scorecard(rows, path)
    return rows
