"""Collect the mission metrics of many episodes into one table.

    python -m sardrone.mission.report --dir data/closed_loop/v1 --name closed_loop_v1

Reads every sidecar in the folder and writes docs/results/<name>.csv (one
row per episode) and docs/results/<name>.md (the totals and the table).
"""

import argparse
import csv
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
RESULTS = PROJECT_ROOT / "docs" / "results"

COLUMNS = [
    "episode_id", "world", "time_of_day", "altitude_m", "occlusion", "detector", "people_placed",
    "people_found", "missed_rescues", "false_reports", "false_alarms", "time_to_first_find_s",
    "mean_report_error_m", "coverage_percent", "cte_mean_m", "cte_max_m", "ade_px", "ade_coasting_px",
    "duration_s", "search_complete",
]  # fmt: skip


def row_from_sidecar(sidecar: dict) -> dict:
    metrics = sidecar.get("mission_metrics") or {}
    cte = metrics.get("cross_track_error") or {}
    ade, coasting = metrics.get("tracker_ade") or {}, metrics.get("tracker_ade_coasting") or {}
    rescues = metrics.get("missed_rescues")
    return {
        "episode_id": sidecar.get("world_id", sidecar["episode_id"]),
        "world": sidecar.get("world", ""),
        "time_of_day": sidecar.get("time_of_day", ""),
        "altitude_m": sidecar.get("altitude_m", ""),
        "occlusion": sidecar.get("occlusion", ""),
        "detector": sidecar.get("detector", ""),
        "people_placed": metrics.get("people_placed", sidecar.get("people_placed", 0)),
        "people_found": metrics.get("people_found", sidecar.get("people_found", 0)),
        "missed_rescues": "" if rescues is None else len(rescues),
        "false_reports": metrics.get("false_reports", ""),
        "false_alarms": metrics.get("false_alarms", ""),
        "time_to_first_find_s": _blank(metrics.get("time_to_first_find_s")),
        "mean_report_error_m": _blank(metrics.get("mean_report_error_m")),
        "coverage_percent": _blank(metrics.get("coverage_percent")),
        "cte_mean_m": _blank(cte.get("mean_m")),
        "cte_max_m": _blank(cte.get("max_m")),
        "ade_px": _blank(ade.get("mean_px")),
        "ade_coasting_px": _blank(coasting.get("mean_px")),
        "duration_s": round(sidecar.get("duration_s", 0.0), 1),
        "search_complete": "yes" if (sidecar.get("event_counts") or {}).get("search_complete") else "no",
    }


def _blank(value):
    return "" if value is None else value


def _numbers(rows: list[dict], key: str) -> list[float]:
    return [float(row[key]) for row in rows if row[key] != ""]


def _mean(values: list[float]) -> str:
    return f"{sum(values) / len(values):.2f}" if values else "n/a"


def totals(rows: list[dict]) -> dict:
    placed = sum(int(r["people_placed"]) for r in rows)
    found = sum(int(r["people_found"]) for r in rows)
    return {
        "episodes": len(rows),
        "people_placed": placed,
        "people_found": found,
        "recall": round(found / placed, 4) if placed else 0.0,
        "missed_rescues": int(sum(_numbers(rows, "missed_rescues"))),
        "false_reports": int(sum(_numbers(rows, "false_reports"))),
        "false_alarms": int(sum(_numbers(rows, "false_alarms"))),
        "episodes_all_found": sum(1 for r in rows if int(r["people_found"]) == int(r["people_placed"])),
        "searches_completed": sum(1 for r in rows if r["search_complete"] == "yes"),
        "mean_time_to_first_find_s": _mean(_numbers(rows, "time_to_first_find_s")),
        "mean_report_error_m": _mean(_numbers(rows, "mean_report_error_m")),
        "mean_coverage_percent": _mean(_numbers(rows, "coverage_percent")),
        "mean_cte_m": _mean(_numbers(rows, "cte_mean_m")),
        "mean_ade_px": _mean(_numbers(rows, "ade_px")),
        "mean_ade_coasting_px": _mean(_numbers(rows, "ade_coasting_px")),
    }


def write_report(rows: list[dict], name: str, title: str, out_dir: Path = RESULTS, note: str = "") -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / f"{name}.csv", "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    summary = totals(rows)
    lines = [f"# {title}", "", "Generated by `sardrone.mission.report`. Do not edit by hand.", ""]
    if note:
        lines += [note, ""]
    lines += ["| | |", "| --- | --- |"]
    labels = {
        "episodes": "Episodes", "searches_completed": "Searches flown to the end",
        "people_placed": "People placed", "people_found": "People found (reported within 3 m)",
        "recall": "Share of people found", "episodes_all_found": "Episodes with everyone found",
        "missed_rescues": "Missed rescues (visible in images, never reported)",
        "false_reports": "False reports (nobody there)", "false_alarms": "False alarms rejected by the orbit",
        "mean_time_to_first_find_s": "Mean time to first find (s)", "mean_report_error_m": "Mean position error (m)",
        "mean_coverage_percent": "Mean coverage (%)", "mean_cte_m": "Mean cross-track error (m)",
        "mean_ade_px": "Tracker ADE, all frames (px)", "mean_ade_coasting_px": "Tracker ADE while coasting (px)",
    }  # fmt: skip
    lines += [f"| {labels[key]} | {summary[key]} |" for key in labels]
    lines += ["", "| " + " | ".join(COLUMNS) + " |", "| " + " | ".join(["---"] * len(COLUMNS)) + " |"]
    lines += ["| " + " | ".join(str(row[c]) for c in COLUMNS) + " |" for row in rows]
    (out_dir / f"{name}.md").write_text("\n".join(lines) + "\n")
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Tabulate mission metrics of a folder of episodes.")
    parser.add_argument("--dir", type=Path, required=True)
    parser.add_argument("--name", required=True, help="output file name under docs/results")
    parser.add_argument("--title", default="Mission metrics")
    parser.add_argument("--note", default="")
    parser.add_argument("--prefix", default="", help="only episodes whose id starts with this")
    args = parser.parse_args(argv)
    rows = []
    for path in sorted(args.dir.glob(f"{args.prefix}*.json")):
        sidecar = json.loads(path.read_text())
        if "mission_metrics" in sidecar:
            rows.append(row_from_sidecar(sidecar))
    if not rows:
        print(f"no episodes with mission metrics in {args.dir}")
        return 1
    print(json.dumps(write_report(rows, args.name, args.title, note=args.note), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
